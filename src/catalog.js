function selectRecipe(occasion = '', hint = '') {
  const text = `${occasion} ${hint}`.trim();
  if (RECIPES.taco.match.test(text)) return RECIPES.taco;
  if (RECIPES.recovery.match.test(text)) return RECIPES.recovery;
  if (RECIPES.breakfast.match.test(text)) return RECIPES.breakfast;
  return RECIPES.staples;
}

function searchProducts(query = '', limit = 8) {
  const terms = String(query)
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((term) => term.length > 2);

  if (terms.length === 0) return [];

  return PRODUCT_CATALOG.map((product) => {
    const haystack = [
      product.name,
      product.brand,
      product.category,
      ...(product.keywords || []),
      ...(product.dietaryTags || []),
    ]
      .join(' ')
      .toLowerCase();

    const score = terms.reduce(
      (total, term) => total + (haystack.includes(term) ? 1 : 0),
      0,
    );
    return { product, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score || a.product.name.localeCompare(b.product.name))
    .slice(0, limit)
    .map((entry) => entry.product);
}

